/** The closing instructions every prompt ends with (SPEC 7.2). */
export function formatInstructions(kind: ImportableKind, answerLanguage: "he" | "en"): string {
  const lang = answerLanguage === "he" ? "עברית" : "אנגלית";
  return [
    `כתוב את התשובה ב${lang}. אפשר להסביר בקצרה בטקסט חופשי.`,
    "",
    "בסוף התשובה הוסף בלוק קוד אחד בדיוק, עם השפה tripdata, ב-JSON תקין, בפורמט הזה:",
    exampleBlock(kind),
    "",
    `- kind חייב להיות "${kind}".`,
    "- שדות:",
    ...FIELD_HELP[kind].map((l) => `  - ${l}`),
    "- בלי הערות ובלי טקסט בתוך הבלוק. בלוק אחד שמכיל את כל הפריטים.",
  ].join("\n");
}
